-- 7. 참가 여부 확인 함수
-- =========================================================

create or replace function public.quiz_is_participant(
  p_room_code text
)
returns boolean

language sql

stable

security definer

set search_path = public

as $$

  select exists(

    select 1

    from public.quiz_players

    where room_code = p_room_code

      and user_id = auth.uid()

      and left_at is null

  );

$$;


revoke all
on function public.quiz_is_participant(text)
from public;


grant execute
on function public.quiz_is_participant(text)
to authenticated;



