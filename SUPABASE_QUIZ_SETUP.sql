create table if not exists public.quiz_questions (
  id integer generated by default as identity primary key,
  question text not null unique,
  options jsonb not null,
  correct_index smallint not null check (correct_index between 0 and 3)
);

-- 문제/정답 테이블도 RLS를 켭니다. 일반 클라이언트는 직접 읽지 못합니다.
alter table public.quiz_questions enable row level security;

create table if not exists public.quiz_rooms (
  code text primary key,
  host_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'waiting' check (status in ('waiting','playing','finished')),
  question_ids integer[] not null default '{}',
  current_question integer not null default -1,
  question_started_at timestamptz,
  winner_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.quiz_players (
  room_code text not null references public.quiz_rooms(code) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  nickname varchar(16) not null,
  ready boolean not null default false,
  score integer not null default 0,
  correct_count integer not null default 0,
  joined_at timestamptz not null default now(),
  left_at timestamptz,
  primary key (room_code, user_id)
);

create table if not exists public.quiz_answers (
  room_code text not null references public.quiz_rooms(code) on delete cascade,
  question_index integer not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  answer_index smallint not null check (answer_index between 0 and 3),
  is_correct boolean not null,
  points integer not null default 0,
  answered_at timestamptz not null default now(),
  primary key (room_code, question_index, user_id)
);

