-- 10. 방 만들기
-- =========================================================

create or replace function public.quiz_create_room(
  p_nickname text
)

returns text

language plpgsql

security definer

set search_path = public

as $$

declare

  v_uid uuid := auth.uid();

  v_code text;

  i integer;

begin

  if v_uid is null then

    raise exception '로그인이 필요합니다.';

  end if;


  if nullif(trim(p_nickname),'') is null then

    raise exception '닉네임이 필요합니다.';

  end if;


  delete from public.quiz_rooms

  where created_at < now() - interval '2 hours';


  for i in 1..20 loop

    v_code := upper(

      substr(

        md5(
          random()::text ||
          clock_timestamp()::text ||
          v_uid::text
        ),

        1,

        6

      )

    );


    exit when not exists(

      select 1

      from public.quiz_rooms

      where code = v_code

    );

  end loop;


  if exists(

    select 1

    from public.quiz_rooms

    where code = v_code

  ) then

    raise exception '방 코드를 만들지 못했습니다.';

  end if;


  insert into public.quiz_rooms(
    code,
    host_id,
    status
  )

  values(
    v_code,
    v_uid,
    'waiting'
  );


  insert into public.quiz_players(
    room_code,
    user_id,
    nickname,
    ready
  )

  values(
    v_code,
    v_uid,
    left(trim(p_nickname),16),
    false
  );


  return v_code;

end;

$$;



-- =========================================================
-- 11. 방 참가
-- =========================================================

create or replace function public.quiz_join_room(
  p_code text,
  p_nickname text
)

returns text

language plpgsql

security definer

set search_path = public

as $$

declare

  v_uid uuid := auth.uid();

  v_code text := upper(trim(p_code));

  v_status text;

  v_count integer;

begin

  if v_uid is null then

    raise exception '로그인이 필요합니다.';

  end if;


  if nullif(trim(p_nickname),'') is null then

    raise exception '닉네임이 필요합니다.';

  end if;


  select status

  into v_status

  from public.quiz_rooms

  where code = v_code

  for update;


  if not found then

    raise exception '존재하지 않는 방 코드입니다.';

  end if;


  if v_status <> 'waiting' then

    raise exception '이미 시작했거나 종료된 방입니다.';

  end if;


  if exists(

    select 1

    from public.quiz_players

    where room_code = v_code

      and user_id = v_uid

  ) then


    update public.quiz_players

    set
      nickname = left(trim(p_nickname),16),
      left_at = null

    where room_code = v_code

      and user_id = v_uid;


    return v_code;

  end if;


  select count(*)

  into v_count

  from public.quiz_players

  where room_code = v_code

    and left_at is null;


  if v_count >= 2 then

    raise exception '이미 두 명이 참가한 방입니다.';

  end if;


  insert into public.quiz_players(
    room_code,
    user_id,
    nickname,
    ready
  )

  values(
    v_code,
    v_uid,
    left(trim(p_nickname),16),
    false
  );


  return v_code;

end;

$$;



-- =========================================================
-- 12. 준비 상태 변경
-- =========================================================

create or replace function public.quiz_set_ready(
  p_code text,
  p_ready boolean
)

returns void

language plpgsql

security definer

set search_path = public

as $$

declare

  v_uid uuid := auth.uid();

  v_status text;

begin


  select status

  into v_status

  from public.quiz_rooms

  where code = upper(trim(p_code));


  if v_status is null then

    raise exception '방을 찾을 수 없습니다.';

  end if;


  if v_status <> 'waiting' then

    raise exception '대기 중인 방에서만 준비할 수 있습니다.';

  end if;


  update public.quiz_players

  set ready = p_ready

  where room_code = upper(trim(p_code))

    and user_id = v_uid

    and left_at is null;


  if not found then

    raise exception '참가자가 아닙니다.';

  end if;

end;

$$;



-- =========================================================
-- 13. 대전 시작
-- 방장만 실행 가능
-- =========================================================

create or replace function public.quiz_start_room(
  p_code text
)

returns void

language plpgsql

security definer

set search_path = public

as $$

declare

  v_uid uuid := auth.uid();

  v_code text := upper(trim(p_code));

  v_host uuid;

  v_status text;

  v_players integer;

  v_ready integer;

  v_ids integer[];

begin


  select
    host_id,
    status

  into
    v_host,
    v_status

  from public.quiz_rooms

  where code = v_code

  for update;


  if not found then

    raise exception '방을 찾을 수 없습니다.';

  end if;


  if v_host <> v_uid then

    raise exception '방장만 시작할 수 있습니다.';

  end if;


  if v_status <> 'waiting' then

    raise exception '이미 시작된 방입니다.';

  end if;


  select
    count(*),
    count(*) filter(where ready)

  into
    v_players,
    v_ready

  from public.quiz_players

  where room_code = v_code

    and left_at is null;


  if v_players <> 2 then

    raise exception '두 명이 모두 입장해야 합니다.';

  end if;


  if v_ready <> 2 then

    raise exception '두 명 모두 준비해야 합니다.';

  end if;


  select array_agg(id order by rnd)

  into v_ids

  from (

    select
      id,
      random() as rnd

    from public.quiz_questions

    order by rnd

    limit 10

  ) q;


  if coalesce(array_length(v_ids,1),0) < 10 then

    raise exception '퀴즈 문제가 부족합니다.';

  end if;


  delete from public.quiz_answers

  where room_code = v_code;


  update public.quiz_players

  set
    score = 0,
    correct_count = 0,
    ready = false

  where room_code = v_code;


  update public.quiz_rooms

  set
    status = 'playing',
    question_ids = v_ids,
    current_question = 0,
    question_started_at = now(),
    winner_id = null,
    updated_at = now()

  where code = v_code;

end;

$$;



-- =========================================================
-- 14. 현재 문제 가져오기
-- 정답은 보내지 않음
-- =========================================================

create or replace function public.quiz_get_current_question(
  p_room_code text
)

returns table(

  question_no integer,

  question_id integer,

  question_text text,

  options jsonb,

  started_at timestamptz,

  room_status text

)

language plpgsql

security definer

set search_path = public

as $$

declare

  v_code text := upper(trim(p_room_code));

  v_idx integer;

  v_ids integer[];

  v_started timestamptz;

  v_status text;

  v_qid integer;

begin


  if not public.quiz_is_participant(v_code) then

    raise exception '참가자가 아닙니다.';

  end if;


  select
    current_question,
    question_ids,
    question_started_at,
    status

  into
    v_idx,
    v_ids,
    v_started,
    v_status

  from public.quiz_rooms

  where code = v_code;


  if not found then

    return;

  end if;


  if v_status <> 'playing'

     or v_idx < 0 then

    return;

  end if;


  v_qid := v_ids[v_idx + 1];


  return query

  select

    v_idx,

    q.id,

    q.question,

    q.options,

    v_started,

    v_status

  from public.quiz_questions q

  where q.id = v_qid;

end;

$$;



-- =========================================================
-- 15. 정답 제출
-- 점수와 정답은 서버에서 계산
-- =========================================================

create or replace function public.quiz_submit_answer(
  p_room_code text,
  p_question_index integer,
  p_answer_index integer
)

returns table(
  result_correct boolean,
  result_points integer,
  result_correct_index integer
)

language plpgsql

security definer

set search_path = public

as $$

declare

  v_uid uuid := auth.uid();

  v_code text := upper(trim(p_room_code));

  v_status text;

  v_idx integer;

  v_ids integer[];

  v_started timestamptz;

  v_qid integer;

  v_correct_idx integer;

  v_correct boolean;

  v_points integer := 0;

  v_correct_before integer := 0;

begin


  if p_answer_index not between 0 and 3 then

    raise exception '잘못된 답안입니다.';

  end if;


  if not public.quiz_is_participant(v_code) then

    raise exception '참가자가 아닙니다.';

  end if;


  select
    status,
    current_question,
    question_ids,
    question_started_at

  into
    v_status,
    v_idx,
    v_ids,
    v_started

  from public.quiz_rooms

  where code = v_code

  for update;


  if not found
     or v_status <> 'playing' then

    raise exception '진행 중인 대전이 아닙니다.';

  end if;


  if v_idx <> p_question_index then

    raise exception '이미 다음 문제로 넘어갔습니다.';

  end if;


  if now() > v_started + interval '12 seconds' then

    raise exception '답변 시간이 끝났습니다.';

  end if;


  if exists(

    select 1

    from public.quiz_answers

    where room_code = v_code

      and question_index = v_idx

      and user_id = v_uid

  ) then

    raise exception '이미 답을 제출했습니다.';

  end if;


  v_qid := v_ids[v_idx + 1];


  select correct_index

  into v_correct_idx

  from public.quiz_questions

  where id = v_qid;


  v_correct := (
    p_answer_index = v_correct_idx
  );


  if v_correct then


    select count(*)

    into v_correct_before

    from public.quiz_answers

    where room_code = v_code

      and question_index = v_idx

      and is_correct = true;


    v_points :=

      case

        when v_correct_before = 0
          then 100

        else 70

      end;

  end if;


  insert into public.quiz_answers(
    room_code,
    question_index,
    user_id,
    answer_index,
    is_correct,
    points
  )

  values(
    v_code,
    v_idx,
    v_uid,
    p_answer_index,
    v_correct,
    v_points
  );


  if v_correct then


    update public.quiz_players

    set
      score = score + v_points,

      correct_count =
        correct_count + 1

    where room_code = v_code

      and user_id = v_uid;

  end if;


  return query

  select

    v_correct,

    v_points,

    v_correct_idx;

end;

$$;



-- =========================================================
-- 16. 다음 문제로 이동
-- 둘 다 답하거나 12초가 지나면 이동
-- =========================================================

create or replace function public.quiz_advance_room(
  p_room_code text
)

returns text

language plpgsql

security definer

set search_path = public

as $$

declare

  v_code text :=
    upper(trim(p_room_code));

  v_status text;

  v_idx integer;

  v_ids integer[];

  v_started timestamptz;

  v_answered integer;

  v_players integer;

  v_top_score integer;

  v_top_count integer;

  v_winner uuid;

begin


  if not public.quiz_is_participant(v_code) then

    raise exception '참가자가 아닙니다.';

  end if;


  select
    status,
    current_question,
    question_ids,
    question_started_at

  into
    v_status,
    v_idx,
    v_ids,
    v_started

  from public.quiz_rooms

  where code = v_code

  for update;


  if not found then

    return 'missing';

  end if;


  if v_status <> 'playing' then

    return v_status;

  end if;


  select count(*)

  into v_players

  from public.quiz_players

  where room_code = v_code

    and left_at is null;


  select count(*)

  into v_answered

  from public.quiz_answers

  where room_code = v_code

    and question_index = v_idx;


  if v_answered < v_players

     and now() <
       v_started + interval '12 seconds'

  then

    return 'playing';

  end if;


  if v_idx >=
     coalesce(array_length(v_ids,1),0) - 1

  then


    select max(score)

    into v_top_score

    from public.quiz_players

    where room_code = v_code

      and left_at is null;


    select count(*)

    into v_top_count

    from public.quiz_players

    where room_code = v_code

      and left_at is null

      and score = v_top_score;


    if v_top_count = 1 then


      select user_id

      into v_winner

      from public.quiz_players

      where room_code = v_code

        and left_at is null

        and score = v_top_score

      limit 1;


    else

      v_winner := null;

    end if;


    update public.quiz_rooms

    set
      status = 'finished',
      winner_id = v_winner,
      updated_at = now()

    where code = v_code;


    return 'finished';

  end if;


  update public.quiz_rooms

  set
    current_question =
      v_idx + 1,

    question_started_at =
      now(),

    updated_at =
      now()

  where code = v_code;


  return 'playing';

end;

$$;



-- =========================================================
-- 17. 방 나가기
-- 진행 중 나가면 상대방 승리
-- =========================================================

create or replace function public.quiz_leave_room(
  p_room_code text
)

returns void

language plpgsql

security definer

set search_path = public

as $$

declare

  v_uid uuid := auth.uid();

  v_code text :=
    upper(trim(p_room_code));

  v_host uuid;

  v_status text;

  v_other uuid;

begin


  select
    host_id,
    status

  into
    v_host,
    v_status

  from public.quiz_rooms

  where code = v_code

  for update;


  if not found then

    return;

  end if;


  if not exists(

    select 1

    from public.quiz_players

    where room_code = v_code

      and user_id = v_uid

      and left_at is null

  ) then

    return;

  end if;


  if v_status = 'waiting' then


    if v_host = v_uid then

      delete from public.quiz_rooms

      where code = v_code;


    else


      delete from public.quiz_players

      where room_code = v_code

        and user_id = v_uid;


    end if;


    return;

  end if;


  if v_status = 'playing' then


    select user_id

    into v_other

    from public.quiz_players

    where room_code = v_code

      and user_id <> v_uid

      and left_at is null

    limit 1;


    update public.quiz_players

    set left_at = now()

    where room_code = v_code

      and user_id = v_uid;


    update public.quiz_rooms

    set
      status = 'finished',

      winner_id = v_other,

      updated_at = now()

    where code = v_code;


    return;

  end if;


  update public.quiz_players

  set left_at = now()

  where room_code = v_code

    and user_id = v_uid;

end;

$$;



